function setupEmojiKeyboardController({
  triggerBtn,
  keyboardEl,
  searchInput,
  clearBtn,
  navEl,
  bodyEl,
  getTargetTextarea,
  onSelectEmoji
}) {
  if (!keyboardEl || !bodyEl) return null;

  function render(filterQuery = '') {
    const q = (filterQuery || '').trim().toLowerCase();
    bodyEl.innerHTML = '';

    if (q) {
      const matches = [];
      EMOJI_CATEGORIES.forEach(cat => {
        cat.emojis.forEach(em => {
          if (em.c.includes(q) || em.n.toLowerCase().includes(q)) {
            matches.push(em);
          }
        });
      });

      if (matches.length === 0) {
        bodyEl.innerHTML = `<div class="emoji-no-results">No emojis matching "${typeof escapeHtml === 'function' ? escapeHtml(filterQuery) : filterQuery}"</div>`;
        return;
      }

      const sec = document.createElement('div');
      sec.className = 'emoji-category-section';
      sec.innerHTML = `<div class="emoji-category-title">Search Results (${matches.length})</div>`;
      const grid = document.createElement('div');
      grid.className = 'emoji-grid';
      matches.forEach(em => {
        const btn = document.createElement('button');
        btn.type = 'button';
        btn.className = 'emoji-btn';
        btn.textContent = em.c;
        btn.title = em.n.split(' ')[0] || em.c;
        btn.dataset.emoji = em.c;
        grid.appendChild(btn);
      });
      sec.appendChild(grid);
      bodyEl.appendChild(sec);
    } else {
      EMOJI_CATEGORIES.forEach(cat => {
        const sec = document.createElement('div');
        sec.className = 'emoji-category-section';
        sec.id = `${bodyEl.id || 'emoji'}-sec-${cat.id}`;
        sec.setAttribute('data-category-id', cat.id);
        sec.innerHTML = `<div class="emoji-category-title">${typeof escapeHtml === 'function' ? escapeHtml(cat.name) : cat.name}</div>`;
        const grid = document.createElement('div');
        grid.className = 'emoji-grid';
        cat.emojis.forEach(em => {
          const btn = document.createElement('button');
          btn.type = 'button';
          btn.className = 'emoji-btn';
          btn.textContent = em.c;
          btn.title = em.n.split(' ')[0] || em.c;
          btn.dataset.emoji = em.c;
          grid.appendChild(btn);
        });
        sec.appendChild(grid);
        bodyEl.appendChild(sec);
      });
    }
  }

  function openKeyboard() {
    keyboardEl.style.display = 'flex';
    if (!keyboardEl.dataset.rendered) {
      keyboardEl.dataset.rendered = 'true';
      render('');
    }
    if (searchInput) {
      searchInput.focus();
    }
  }

  function closeKeyboard() {
    keyboardEl.style.display = 'none';
  }

  function toggleKeyboard() {
    if (keyboardEl.style.display === 'none' || !keyboardEl.style.display) {
      openKeyboard();
    } else {
      closeKeyboard();
    }
  }

  if (triggerBtn && !triggerBtn.dataset.eventsBound) {
    triggerBtn.dataset.eventsBound = 'true';
    triggerBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      toggleKeyboard();
    });
  }

  if (bodyEl && !bodyEl.dataset.eventsBound) {
    bodyEl.dataset.eventsBound = 'true';
    bodyEl.addEventListener('click', (e) => {
      const btn = e.target.closest('.emoji-btn');
      if (!btn) return;
      e.stopPropagation();
      const emoji = btn.dataset.emoji || btn.textContent;
      const targetTextarea = typeof getTargetTextarea === 'function' ? getTargetTextarea() : null;
      if (targetTextarea && emoji) {
        const start = targetTextarea.selectionStart !== undefined ? targetTextarea.selectionStart : targetTextarea.value.length;
        const end = targetTextarea.selectionEnd !== undefined ? targetTextarea.selectionEnd : targetTextarea.value.length;
        const val = targetTextarea.value;
        targetTextarea.value = val.substring(0, start) + emoji + val.substring(end);
        const newPos = start + emoji.length;
        targetTextarea.selectionStart = targetTextarea.selectionEnd = newPos;
        targetTextarea.focus();
      }
      if (typeof onSelectEmoji === 'function') {
        onSelectEmoji(emoji);
      }
    });
  }

  if (searchInput && !searchInput.dataset.eventsBound) {
    searchInput.dataset.eventsBound = 'true';
    searchInput.addEventListener('input', () => {
      const val = searchInput.value;
      if (clearBtn) {
        clearBtn.style.display = val ? 'inline-block' : 'none';
      }
      render(val);
    });
    searchInput.addEventListener('keydown', (e) => {
      if (e.key === 'Escape') {
        e.stopPropagation();
        closeKeyboard();
        const targetTextarea = typeof getTargetTextarea === 'function' ? getTargetTextarea() : null;
        if (targetTextarea) targetTextarea.focus();
      }
    });
  }

  if (clearBtn && !clearBtn.dataset.eventsBound) {
    clearBtn.dataset.eventsBound = 'true';
    clearBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      if (searchInput) {
        searchInput.value = '';
        searchInput.focus();
      }
      clearBtn.style.display = 'none';
      render('');
    });
  }

  if (navEl && !navEl.dataset.eventsBound) {
    navEl.dataset.eventsBound = 'true';
    navEl.addEventListener('click', (e) => {
      const btn = e.target.closest('.emoji-nav-btn');
      if (!btn) return;
      e.stopPropagation();
      const catId = btn.dataset.category;
      if (!catId) return;

      if (searchInput && searchInput.value) {
        searchInput.value = '';
        if (clearBtn) clearBtn.style.display = 'none';
        render('');
      }

      navEl.querySelectorAll('.emoji-nav-btn').forEach(b => b.classList.remove('is-active'));
      btn.classList.add('is-active');

      const sec = bodyEl.querySelector(`[data-category-id="${catId}"]`);
      if (sec && bodyEl) {
        sec.scrollIntoView({ behavior: 'smooth', block: 'start' });
      }
    });
  }

  return {
    render,
    open: openKeyboard,
    close: closeKeyboard,
    toggle: toggleKeyboard
  };
}

window.setupEmojiKeyboardController = setupEmojiKeyboardController;
